package lab

import (
	"fmt"
	"regexp"
	"strings"
)

// safeConfigToken matches the restricted charset this generator allows to
// be interpolated into nats.conf: generated tokens, identifiers, and MQTT
// topic segments. It intentionally excludes quotes, braces, and
// whitespace so no caller-supplied value can break out of a quoted string
// or inject new config stanzas.
var safeConfigToken = regexp.MustCompile(`^[A-Za-z0-9_\-./:]+$`)

// MQTTTopicToNATSSubject converts an MQTT topic filter into the NATS
// subject space the broker's MQTT integration maps it to (NATS translates
// MQTT topic levels by replacing "/" with ".").
func MQTTTopicToNATSSubject(topic string) string {
	return strings.ReplaceAll(topic, "/", ".")
}

// NATSConfigParams are the values substituted into the generated nats.conf.
// All fields must pass safeConfigToken; RenderNATSConfig rejects anything
// else rather than attempting to escape it.
type NATSConfigParams struct {
	MQTTListenAddr  string
	HTTPMonitorAddr string
	JetStreamDir    string
	PublisherUser   string
	PublisherPass   string
	BridgeUser      string
	BridgePass      string
	CommandSubject  string
}

func validateToken(name, value string) error {
	if value == "" || !safeConfigToken.MatchString(value) {
		return fmt.Errorf("lab: %s contains unsupported characters for generated config", name)
	}
	return nil
}

// RenderNATSConfig produces a minimal nats.conf: JetStream-backed MQTT
// 3.1.1 QoS 1 support, and a single shared account holding both lab users
// so the publisher's command actually reaches the bridge (NATS subject
// space is isolated per account, and this config defines no
// imports/exports, so two separate accounts would never let the one
// subject flow between them). The publisher user is publish-only on the
// single command subject; the bridge user is subscribe-only on that same
// subject; all other subjects are denied by default for both.
func RenderNATSConfig(p NATSConfigParams) (string, error) {
	fields := map[string]string{
		"MQTTListenAddr":  p.MQTTListenAddr,
		"HTTPMonitorAddr": p.HTTPMonitorAddr,
		"JetStreamDir":    p.JetStreamDir,
		"PublisherUser":   p.PublisherUser,
		"PublisherPass":   p.PublisherPass,
		"BridgeUser":      p.BridgeUser,
		"BridgePass":      p.BridgePass,
		"CommandSubject":  p.CommandSubject,
	}
	for name, value := range fields {
		if err := validateToken(name, value); err != nil {
			return "", err
		}
	}

	conf := fmt.Sprintf(`# Generated by dsx-lab init. Do not edit by hand; re-run init to regenerate.
jetstream {
  store_dir: "%s"
}
mqtt {
  listen: "%s"
}
http: "%s"
accounts: {
  GRIDMETRY: {
    jetstream: enabled
    users: [
      {
        user: "%s"
        password: "%s"
        permissions: {
          publish: { allow: ["%s"] }
          subscribe: { deny: [">"] }
        }
      }
      {
        user: "%s"
        password: "%s"
        permissions: {
          subscribe: { allow: ["%s"] }
          publish: { deny: [">"] }
        }
      }
    ]
  }
}
`, p.JetStreamDir, p.MQTTListenAddr, p.HTTPMonitorAddr,
		p.PublisherUser, p.PublisherPass, p.CommandSubject,
		p.BridgeUser, p.BridgePass, p.CommandSubject)
	return conf, nil
}
